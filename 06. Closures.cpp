function<int()> getDanglingClosure()
{
 int local_var = 5;
 return [&local_var](){
    return local_var;
 };
}

int main()
{
 int factor, value;
 cin>>factor>>value;
 auto my_closure = [factor](int x){
   return factor*x;
 };
 cout<<my_closure(value)<<endl;
 auto bad_closure = getDanglingClosure();
 auto x = bad_closure();
 /* UNDEFINED BEHAVIOR: Reading 'result' will output garbage values or crash, 
    because it tried to read memory that was already deallocated. */ 
 cout<<x<<endl;
 return 0;
}