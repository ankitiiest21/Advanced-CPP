/*Closure is a runtime object created by the lambda expression.
  Lambda expression: actual compile-time syntax we write in our code.
  (e.g., [](int x){ return x+1; })
  Closure: concrete runtime object generated by the compile when that 
  lambda expression is executed.
*/
